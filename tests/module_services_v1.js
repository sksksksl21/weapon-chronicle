"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../src/core/module_services_v1.js"),"utf8");
const sandbox={};
vm.createContext(sandbox);
vm.runInContext(source,sandbox);
const modules=vm.runInContext("WC_GAME_MODULES_V1",sandbox);
assert.equal(modules.has("equipment"),false);
assert.throws(()=>modules.require("equipment"),/Missing game module dependency/);
assert.throws(()=>modules.register("../escape",{}),/Invalid game module id/);
assert.throws(()=>modules.register("empty",null),/Module API must be/);
const api=Object.freeze({rollCopy:()=>1});
assert.strictEqual(modules.register("equipment",api),api);
assert.strictEqual(modules.require("equipment"),api);
assert.deepEqual(Array.from(modules.list()),["equipment"]);
assert.throws(()=>modules.register("equipment",{}),/Duplicate game module/);
assert.equal(modules.require("equipment").rollCopy(),1);
assert(Object.isFrozen(modules.list()));
console.log("PASS: explicit module dependency contract");
